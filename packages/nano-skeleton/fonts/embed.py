"""
Embed the built fonts as base64:

- into ../src/fonts.ts, replacing the "data" strings of the "words" (Blocks)
  and "lines" (Blocks Solid) entries. The script registers them.
- into ../src/fonts.css, as @font-face rules for the stylesheet that works
  before the elements are defined.
"""
import base64
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
TARGET = HERE.parent / "src" / "fonts.ts"
CSS_TARGET = HERE.parent / "src" / "fonts.css"
FONTS = {"words": "Blocks-VF.woff2", "lines": "BlocksSolid-VF.woff2"}

source = TARGET.read_text()
faces = []
for key, file in FONTS.items():
    data = base64.b64encode((HERE / file).read_bytes()).decode("ascii")
    source, count = re.subn(
        rf'({key}: \{{[^}}]*?data: ")[^"]*(")',
        lambda match: match.group(1) + data + match.group(2),
        source,
    )
    if count != 1:
        raise SystemExit(f'Expected one "{key}" entry in {TARGET}, found {count}')
    faces.append(
        "@font-face {\n"
        f"  font-family: nano-skeleton-font-{key};\n"
        f'  src: url("data:font/woff2;base64,{data}") format("woff2");\n'
        "  font-display: block;\n"
        "}\n"
    )
    print(f"{key}: {file}, {(HERE / file).stat().st_size} bytes")
TARGET.write_text(source)
CSS_TARGET.write_text(
    "/**\n"
    " * Generated by fonts/embed.py, don't edit. The built-in fonts of\n"
    " * src/fonts.ts, for the stylesheet that works before the elements are\n"
    " * defined. The text they draw is transparent, so blocking rendering until\n"
    " * they're parsed avoids flashing a fallback font.\n"
    " */\n" + "\n".join(faces)
)
